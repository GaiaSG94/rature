import { useState } from 'react'
import { origineExercice } from '../../domain/banque'
import { libelleDe } from '../../domain/taxonomy'
import { Bouton } from '../components/Bouton'
import { Carte } from '../components/Carte'
import { useRature } from '../../etat/useRature'

/**
 * Écran 6 : l'exercice ciblé. La solution est masquée par défaut — l'app
 * entraîne, elle ne donne jamais la réponse (§10).
 */
export function Exercice() {
  const { resultat, nouvelExercice, occupe, aller } = useRature()
  const [reponse, setReponse] = useState('')
  const [solutionVue, setSolutionVue] = useState(false)
  const [indicesVus, setIndicesVus] = useState(false)

  const verifie = resultat?.exercice
  if (!verifie) {
    return (
      <div className="space-y-4">
        <h1 className="text-2xl font-bold tracking-tight">Targeted exercise</h1>
        <p className="text-sm text-muet">
          {resultat?.messageExercice ?? 'No exercise yet: analyse a paper first.'}
        </p>
        <Bouton onClick={() => aller('cadrage')}>Photograph a paper</Bouton>
      </div>
    )
  }

  const { exercice, verdict } = verifie
  return (
    <div className="space-y-5">
      <h1 className="text-2xl font-bold tracking-tight">Work on: {libelleDe(exercice.typeTravaille)}</h1>
      <p className="text-sm text-muet">
        One goal, not a whole chapter. Level: {exercice.niveau}.
      </p>

      <Carte titre="Statement" ton="jaune">
        <p className="lecture whitespace-pre-wrap text-base text-texte">{exercice.enonce}</p>
      </Carte>

      <div className="flex flex-wrap gap-3">
        <Bouton variante="secondaire" onClick={() => setIndicesVus((vu) => !vu)}>
          {indicesVus ? 'Hide hints' : 'See a hint'}
        </Bouton>
        <Bouton variante="discret" onClick={() => setSolutionVue((vue) => !vue)}>
          {solutionVue ? 'Hide the solution' : 'See the solution'}
        </Bouton>
      </div>

      {indicesVus && exercice.indices.length > 0 ? (
        <Carte>
          <ul className="list-inside list-disc space-y-1 text-sm text-muet">
            {exercice.indices.map((indice) => (
              <li key={indice}>{indice}</li>
            ))}
          </ul>
        </Carte>
      ) : null}

      <Carte titre="Your answer">
        <textarea
          value={reponse}
          onChange={(event) => setReponse(event.target.value)}
          rows={4}
          className="w-full rounded-lg border border-bord bg-surface-2 p-3 text-texte"
          placeholder="Write your working here. Nothing is saved to a server."
        />
      </Carte>

      {solutionVue ? (
        <Carte titre="Solution" ton="vert">
          <p className="lecture whitespace-pre-wrap text-sm text-texte">{exercice.solution}</p>
        </Carte>
      ) : null}

      <p className="text-xs text-muet">{origineExercice(exercice)}</p>

      <Carte>
        <p className="text-xs text-muet">
          Guardrail: this exercise was checked on three points — it really works on
          "{libelleDe(exercice.typeTravaille)}", it does not give away the solution to your
          original exercise, and it is at your level ({verdict.motifs.length > 0 ? `reason: ${verdict.motifs[0]}` : 'all three checked'}).
        </p>
      </Carte>

      <div className="space-y-2">
        <Bouton onClick={() => void nouvelExercice()} disabled={occupe} pleineLargeur>
          {occupe ? 'Preparing…' : 'Another exercise (local bank, instant)'}
        </Bouton>
        <div className="text-center">
          <Bouton variante="discret" onClick={() => void nouvelExercice({ inedit: true })} disabled={occupe}>
            Fresh exercise, generated by the model (slow)
          </Bouton>
        </div>
      </div>
    </div>
  )
}
